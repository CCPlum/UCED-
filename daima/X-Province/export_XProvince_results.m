function export_XProvince_results(results)
%EXPORT_XINJIANG_RESULTS 将全年汇总和机组级结果集中导出。

cfg = results.cfg;
outDir = cfg.runDir;
nHours = numel(results.time);
optimizationBlock = ceil((1:nHours)'/cfg.hoursPerBlock);
hourInBlock = mod((0:nHours-1)',cfg.hoursPerBlock) + 1;

hourly = table(results.time,optimizationBlock,hourInBlock, ...
    results.loadMW,results.windAvailMW,results.solarAvailMW, ...
    results.pCoal,results.pGas,results.pHydro,results.pWind,results.pSolar, ...
    results.storageDischarge,-results.storageCharge,results.storageSOC, ...
    results.windCurtailment,results.solarCurtailment,results.nse, ...
    results.reserveUpRequired,results.reserveUpProvided, ...
    results.reserveDownRequired,results.reserveDownProvided,results.hourlyCost, ...
    'VariableNames',{'Time','OptimizationBlock','HourInBlock', ...
    'Load_MW','WindAvailable_MW','SolarAvailable_MW', ...
    'Coal_MW','Gas_MW','Hydro_MW','Wind_MW','Solar_MW', ...
    'StorageDischarge_MW','StorageCharge_MW','StorageSOC_MWh', ...
    'WindCurtailment_MW','SolarCurtailment_MW','NSE_MW', ...
    'ReserveUpRequired_MW','ReserveUpProvided_MW', ...
    'ReserveDownRequired_MW','ReserveDownProvided_MW','HourlyCost'});
validationTable = struct2table(results.validation,'AsArray',true);

%% 可选CSV（默认关闭，保持结果目录简洁）
if cfg.writeCSVFiles
    writetable(hourly,fullfile(outDir,'hourly_dispatch_summary.csv'));
    writetable(results.blocks,fullfile(outDir,'block_solve_status.csv'));
    writetable(validationTable,fullfile(outDir,'validation_summary.csv'));
    writetable(results.thermal,fullfile(outDir,'xinjiang_thermal_units_used.csv'));
    writetable(results.hydro,fullfile(outDir,'xinjiang_hydro_units_used.csv'));
    writetable(results.storage,fullfile(outDir,'xinjiang_storage_units_used.csv'));
end

if cfg.writeUnitCSV
    writeWideMatrix(fullfile(outDir,'thermal_unit_power_MW.csv'), ...
        results.time,results.pThermalUnit,string(results.thermal.Resource));
    writeWideMatrix(fullfile(outDir,'thermal_unit_commitment.csv'), ...
        results.time,round(results.commitmentUnit),string(results.thermal.Resource));
    writeWideMatrix(fullfile(outDir,'thermal_unit_startup.csv'), ...
        results.time,round(results.startupUnit),string(results.thermal.Resource));
    writeWideMatrix(fullfile(outDir,'hydro_unit_power_MW.csv'), ...
        results.time,results.pHydroUnit,string(results.hydro.Resource));
    writeWideMatrix(fullfile(outDir,'storage_unit_charge_MW.csv'), ...
        results.time,-results.storageChargeUnit,string(results.storage.Resource));
    writeWideMatrix(fullfile(outDir,'storage_unit_discharge_MW.csv'), ...
        results.time,results.storageDischargeUnit,string(results.storage.Resource));
    writeWideMatrix(fullfile(outDir,'storage_unit_SOC_MWh.csv'), ...
        results.time,results.storageSOCUnit,string(results.storage.Resource));
end

%% 单一Excel工作簿
if cfg.writeExcelWorkbook
    workbookPath = fullfile(outDir,sprintf('Xinjiang_UCED_%d_full_year.xlsx',cfg.year));
    if isfile(workbookPath)
        delete(workbookPath);
    end
    writetable(buildSummaryTable(results),workbookPath,'Sheet','Summary');
    writetable(buildAssumptionTable(results),workbookPath,'Sheet','Assumptions');
    writetable(buildWeeklySummary(results,optimizationBlock),workbookPath, ...
        'Sheet','Weekly_Summary');
    writetable(hourly,workbookPath,'Sheet','Hourly_All');
    writetable(results.blocks,workbookPath,'Sheet','Block_Status');
    writetable(validationTable,workbookPath,'Sheet','Validation');
    writetable(results.thermal,workbookPath,'Sheet','Thermal_Units');
    writetable(results.hydro,workbookPath,'Sheet','Hydro_Units');
    writetable(results.storage,workbookPath,'Sheet','Storage_Units');
    if cfg.writeUnitTimeSeriesToExcel
        writeWideSheet(workbookPath,'Thermal_Power',results.time, ...
            results.pThermalUnit,string(results.thermal.Resource));
        writeWideSheet(workbookPath,'Thermal_Commit',results.time, ...
            round(results.commitmentUnit),string(results.thermal.Resource));
        writeWideSheet(workbookPath,'Thermal_Start',results.time, ...
            round(results.startupUnit),string(results.thermal.Resource));
        writeWideSheet(workbookPath,'Hydro_Power',results.time, ...
            results.pHydroUnit,string(results.hydro.Resource));
    end
    writeWideSheet(workbookPath,'Storage_Charge',results.time, ...
        -results.storageChargeUnit,string(results.storage.Resource));
    writeWideSheet(workbookPath,'Storage_Discharge',results.time, ...
        results.storageDischargeUnit,string(results.storage.Resource));
    writeWideSheet(workbookPath,'Storage_SOC',results.time, ...
        results.storageSOCUnit,string(results.storage.Resource));
end

%% 文本假设说明
fid = fopen(fullfile(outDir,'run_assumptions.txt'),'w','n','UTF-8');
cleanup = onCleanup(@() fclose(fid));
fprintf(fid,'XProvince 2025 单区域 UCED - 运行假设\n');
fprintf(fid,'运行区间：%s 至 %s，共 %d 小时\n',string(results.time(1)),string(results.time(end)),nHours);
fprintf(fid,'完整168小时周：%d；滚动优化块：%d（最后一块为%d小时）\n', ...
    floor(nHours/168),height(results.blocks),mod(nHours-1,168)+1);
fprintf(fid,'不考虑外送负荷、跨区交易和新疆内部网络约束。\n');
fprintf(fid,'煤电统一计划检修折减：%.2f%%\n',100*cfg.thermalDerateFraction);
fprintf(fid,'煤价：%.6f 成本单位/MMBtu（正式研究需替换）\n',cfg.coalFuelCostPerMMBtu);
fprintf(fid,'气价：%.6f 成本单位/MMBtu（当前机组表无气电，正式研究需替换）\n',cfg.gasFuelCostPerMMBtu);
fprintf(fid,'上/下备用负荷系数：%.2f%%；新能源系数：%.2f%%\n', ...
    100*cfg.loadReserveFraction,100*cfg.renewableReserveFraction);
fprintf(fid,'常规水电周容量因子上限：%.2f%%（缺少逐小时入流时的代理）\n', ...
    100*cfg.hydroWeeklyCapacityFactor);
fprintf(fid,'储能初始SOC：%.2f%%；抽蓄循环：%s；新型储能循环：%s\n', ...
    100*cfg.storageInitialSOCFraction,cfg.pumpedStorageCycle,cfg.newStorageCycle);
fprintf(fid,'新增新型储能：%.1f MW / %.1f MWh；充/放电效率：%.4f / %.4f\n', ...
    cfg.newStoragePowerMW,cfg.newStorageEnergyMWh, ...
    cfg.newStorageChargeEfficiency,cfg.newStorageDischargeEfficiency);
fprintf(fid,'代表性供暖期（采用乌鲁木齐日期）：%02d-%02d 至次年 %02d-%02d；CHP内部开机约束启用：%d\n', ...
    cfg.heatingSeasonStart(1),cfg.heatingSeasonStart(2), ...
    cfg.heatingSeasonEnd(1),cfg.heatingSeasonEnd(2),cfg.enableCHPHeating);
fprintf(fid,'结果分类：CHP不单独展示，全部并入Coal_MW；Gas_MW单独展示。\n');
fprintf(fid,'充电符号：Excel中储能充电功率按用电负荷记为负数。\n');
fprintf(fid,'风光曲线超过机组表装机时截断：%d\n',cfg.capVREAtInstalledCapacity);
fprintf(fid,'总目标函数：%.6f\n',results.totalObjective);
fprintf(fid,'总未满足电量：%.6f MWh\n',results.totalNSE_MWh);
fprintf(fid,'总弃风/弃光：%.6f / %.6f MWh\n', ...
    results.totalWindCurtailment_MWh,results.totalSolarCurtailment_MWh);
end

function summary = buildSummaryTable(results)
cfg = results.cfg;
metric = ["Model year";"Start time";"End time";"Hours"; ...
    "Complete 168-hour weeks";"Tail hours";"Optimization blocks"; ...
    "Total objective";"Total NSE (MWh)";"Wind curtailment (MWh)"; ...
    "Solar curtailment (MWh)";"Storage power (MW)";"Storage energy (MWh)"; ...
    "Full unit time series"];
value = [string(cfg.year);string(results.time(1));string(results.time(end)); ...
    string(numel(results.time));string(floor(numel(results.time)/168)); ...
    string(mod(numel(results.time),168));string(height(results.blocks)); ...
    string(results.totalObjective);string(results.totalNSE_MWh); ...
    string(results.totalWindCurtailment_MWh); ...
    string(results.totalSolarCurtailment_MWh); ...
    string(sum(double(results.storage.Existing_Cap_MW))); ...
    string(sum(double(results.storage.Existing_Cap_MWh))); ...
    "Stored in xinjiang_uced_results.mat"];
summary = table(metric,value,'VariableNames',{'Metric','Value'});
end

function weekly = buildWeeklySummary(results,optimizationBlock)
nBlocks = height(results.blocks);
block = (1:nBlocks)';
hoursInBlock = zeros(nBlocks,1);
loadMWh = zeros(nBlocks,1);
coalMWh = zeros(nBlocks,1);
gasMWh = zeros(nBlocks,1);
hydroMWh = zeros(nBlocks,1);
windMWh = zeros(nBlocks,1);
solarMWh = zeros(nBlocks,1);
storageDischargeMWh = zeros(nBlocks,1);
storageChargeMWh = zeros(nBlocks,1);
windCurtailmentMWh = zeros(nBlocks,1);
solarCurtailmentMWh = zeros(nBlocks,1);
nseMWh = zeros(nBlocks,1);
totalCost = zeros(nBlocks,1);
for b = 1:nBlocks
    k = optimizationBlock == b;
    hoursInBlock(b) = nnz(k);
    loadMWh(b) = sum(results.loadMW(k));
    coalMWh(b) = sum(results.pCoal(k));
    gasMWh(b) = sum(results.pGas(k));
    hydroMWh(b) = sum(results.pHydro(k));
    windMWh(b) = sum(results.pWind(k));
    solarMWh(b) = sum(results.pSolar(k));
    storageDischargeMWh(b) = sum(results.storageDischarge(k));
    storageChargeMWh(b) = -sum(results.storageCharge(k));
    windCurtailmentMWh(b) = sum(results.windCurtailment(k));
    solarCurtailmentMWh(b) = sum(results.solarCurtailment(k));
    nseMWh(b) = sum(results.nse(k));
    totalCost(b) = sum(results.hourlyCost(k));
end
weekly = table(block,results.blocks.StartTime,results.blocks.EndTime,hoursInBlock, ...
    loadMWh,coalMWh,gasMWh,hydroMWh,windMWh,solarMWh, ...
    storageDischargeMWh,storageChargeMWh,windCurtailmentMWh, ...
    solarCurtailmentMWh,nseMWh,totalCost, ...
    'VariableNames',{'OptimizationBlock','StartTime','EndTime','Hours', ...
    'Load_MWh','Coal_MWh','Gas_MWh','Hydro_MWh','Wind_MWh','Solar_MWh', ...
    'StorageDischarge_MWh','StorageCharge_MWh','WindCurtailment_MWh', ...
    'SolarCurtailment_MWh','NSE_MWh','TotalCost'});
end

function assumptions = buildAssumptionTable(results)
cfg = results.cfg;
parameter = ["Region model";"External export";"Thermal derate"; ...
    "Coal fuel cost";"Gas fuel cost";"Load reserve";"Renewable reserve"; ...
    "Hydro weekly capacity factor";"Pumped storage cycle"; ...
    "New storage power";"New storage energy";"New storage charge efficiency"; ...
    "New storage discharge efficiency";"New storage cycle"; ...
    "Representative heating season";"CHP reporting"];
value = ["Xinjiang single node";"Not included";string(cfg.thermalDerateFraction); ...
    string(cfg.coalFuelCostPerMMBtu);string(cfg.gasFuelCostPerMMBtu); ...
    string(cfg.loadReserveFraction);string(cfg.renewableReserveFraction); ...
    string(cfg.hydroWeeklyCapacityFactor);string(cfg.pumpedStorageCycle); ...
    string(cfg.newStoragePowerMW);string(cfg.newStorageEnergyMWh); ...
    string(cfg.newStorageChargeEfficiency);string(cfg.newStorageDischargeEfficiency); ...
    string(cfg.newStorageCycle); ...
    sprintf('%02d-%02d to %02d-%02d',cfg.heatingSeasonStart(1), ...
        cfg.heatingSeasonStart(2),cfg.heatingSeasonEnd(1),cfg.heatingSeasonEnd(2)); ...
    "CHP included in Coal_MW"];
unit = ["";"";"fraction";"cost/MMBtu";"cost/MMBtu";"fraction"; ...
    "fraction";"fraction";"";"MW";"MWh";"fraction";"fraction";"";"";""];
assumptions = table(parameter,value,unit,'VariableNames',{'Parameter','Value','Unit'});
end

function writeWideSheet(workbookPath,sheetName,time,matrixByUnit,resourceNames)
if isempty(matrixByUnit)
    return;
end
names = matlab.lang.makeUniqueStrings(matlab.lang.makeValidName(cellstr(resourceNames)));
tbl = array2table(matrixByUnit','VariableNames',names);
tbl = addvars(tbl,time,'Before',1,'NewVariableNames','Time');
writetable(tbl,workbookPath,'Sheet',sheetName);
end

function writeWideMatrix(pathValue,time,matrixByUnit,resourceNames)
if isempty(matrixByUnit)
    return;
end
names = matlab.lang.makeUniqueStrings(matlab.lang.makeValidName(cellstr(resourceNames)));
tbl = array2table(matrixByUnit','VariableNames',names);
tbl = addvars(tbl,time,'Before',1,'NewVariableNames','Time');
writetable(tbl,pathValue);
end
